// Generator: status/compliance.json — the compliance ledger that the SPEC-08-REFERENCE
// `Edges (-> blueprint)` lines point at. It is DERIVED, never hand-authored:
//   contracts/                 -> the machine-readable interface set
//   status/capabilities.json   -> the audited capability statuses
//   status/counts.json         -> the single-sourced program numbers
// Run:  node scripts/docs/gen-compliance.mjs   (from docs/)
// The matching gate (check-compliance.mjs) re-runs this derivation and fails on drift.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';

const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

// 1. Contracts — every machine-readable interface declared on disk.
const contractFiles = readdirSync('contracts')
  .filter((f) => f.endsWith('.json') || f.endsWith('.yaml'))
  .sort();
const contracts = contractFiles.map((f) => {
  const path = `contracts/${f}`;
  let id = null, title = null;
  if (f.endsWith('.json')) {
    const j = readJson(path);
    id = j.$id || null;
    title = j.title || null;
  } else if (f.endsWith('.yaml')) {
    // YAML contracts carry no JSON $id; the path is the id and the top-level `title:` is the title.
    id = path;
    const m = readFileSync(path, 'utf8').match(/^\s*title:\s*(.+)$/m);
    title = m ? m[1].trim() : null;
  }
  return { path, id, title, present: existsSync(path) };
});

// 2. Capabilities — the audited implementation statuses.
const caps = readJson('status/capabilities.json');
const capabilityList = (caps.capabilities || []).map((c) => ({
  id: c.id,
  title: c.title,
  status: c.status,
}));
const statusCounts = {};
for (const c of capabilityList) statusCounts[c.status] = (statusCounts[c.status] || 0) + 1;

// 3. Program numbers (single-sourced).
const counts = readJson('status/counts.json');

const out = {
  schema: 'compliance/v1',
  note: 'DERIVED — generated by scripts/docs/gen-compliance.mjs from contracts/ + status/capabilities.json + status/counts.json. Do not edit by hand; the check-compliance gate re-derives and fails on drift.',
  generated_from: ['contracts/', 'status/capabilities.json', 'status/counts.json'],
  contract_count: contracts.length,
  contracts,
  capability_count: capabilityList.length,
  capability_status_counts: statusCounts,
  capabilities: capabilityList,
  program_numbers: {
    adrs: counts.adrs,
    core_commands: counts.core_commands,
    rbac_layers: counts.rbac_layers,
    ranks: counts.ranks,
    module_tiers: counts.module_tiers,
    license_states: counts.license_states,
    deferred_greenfield: counts.deferred_greenfield,
    logged_deviations: counts.logged_deviations,
  },
};

writeFileSync('status/compliance.json', JSON.stringify(out, null, 2) + '\n');
console.log(`OK: status/compliance.json written (${contracts.length} contracts, ${capabilityList.length} capabilities)`);
